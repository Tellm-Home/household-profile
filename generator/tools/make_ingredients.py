have = {f[:-4] for f in os.listdir(ILL) if f.endswith(".png")}
rows = []
for cat, items in ROWS.items():
    for file, name, aliases, prio, stand in items:
        rows.append({"file": file, "name": name, "category": cat, "aliases": aliases, "priority": prio,
                     "stand_in": stand, "have": "yes" if file in have else "no"})
with open(os.path.join(ROOT, "library", "ingredients.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=["file", "name", "category", "aliases", "priority", "stand_in", "have"])
    w.writeheader(); w.writerows(rows)

todo = [r for r in rows if r["have"] == "no"]
md = ["# Ingredient library", "",
      f"{len(rows)} ingredients. {len(rows) - len(todo)} are drawn; {len(todo)} are still to make "
      f"({sum(r['priority']=='P1' for r in todo)} P1, {sum(r['priority']=='P2' for r in todo)} P2, {sum(r['priority']=='P3' for r in todo)} P3).", "",
      "**How a new picture goes live:** save it as `library/illustrations/<file>.png`, using the file name below. Give it a transparent background, cropped tight, at least 150 px tall. The next build picks it up wherever a household's data mentions any of its names. Nothing in the code needs to change.", "",
      "**Stand-in** is the existing picture the page uses until the real one exists. A blank stand-in shows a placeholder icon, and `report.json` lists the ingredient.", "",
      "## Still to make", ""]
for p in ("P1", "P2", "P3"):
    xs = [r for r in todo if r["priority"] == p]
    md += [f"### {p} · {len(xs)}", "", "| Ingredient | File name | Also called | Stand-in |", "|---|---|---|---|"]
    md += [f"| {r['name']} | `{r['file']}.png` | {r['aliases'].replace('|', ', ')} | {r['stand_in'] or 'none'} |" for r in xs] + [""]
md += ["## Already in the library", "", "| Category | Ingredients |", "|---|---|"]
for cat in ROWS:
    xs = [r["name"] for r in rows if r["category"] == cat and r["have"] == "yes"]
    if xs: md.append(f"| {cat} | {', '.join(xs)} |")
open(os.path.join(ROOT, "library", "ingredients.md"), "w").write("\n".join(md) + "\n")
print(len(rows), "rows;", len(todo), "to make")
